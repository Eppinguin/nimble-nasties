/* Writes src/fonts.css from the Fontsource packages: the Latin and Latin Extended
 * faces only, woff2 only (every browser the app supports reads it). Other scripts
 * fall back to the system font. Run `pnpm fonts` after upgrading a @fontsource package. */
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';

const require = createRequire(import.meta.url);
const FACES = ['alegreya/800', 'alegreya/900', 'barlow-condensed/500', 'barlow-condensed/600', 'barlow-condensed/700', 'barlow-condensed/800', 'barlow-semi-condensed/400', 'barlow-semi-condensed/400-italic', 'barlow-semi-condensed/500', 'barlow-semi-condensed/600'];
const SUBSETS = /-latin(?:-ext)?-\d/;

const blocks = FACES.flatMap((face) => {
  const [family] = face.split('/');
  const css = readFileSync(require.resolve(`@fontsource/${face}.css`), 'utf8');
  return [...css.matchAll(/\/\* ([^*]+) \*\/\s*@font-face \{[^}]+\}/g)].filter((m) => SUBSETS.test(m[1])).map((m) => m[0].replace(/, url\([^)]+\.woff\) format\('woff'\)/, '').replace(/url\(\.\/files\//, `url(@fontsource/${family}/files/`));
});
const header = '/* Self-hosted so the app works offline and no font request leaves the device.\n * Generated by scripts/fonts.ts (`pnpm fonts`): Latin and Latin Extended, woff2 only. */\n';
writeFileSync(new URL('../src/fonts.css', import.meta.url), `${header}\n${blocks.join('\n\n')}\n`);
console.log(`src/fonts.css: ${blocks.length} faces`);
